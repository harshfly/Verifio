"""
AI content detection module — Phase 5 (Grok AI Powered)
Uses the Grok AI (xAI) API to analyze text for AI-generated content.
Falls back to statistical heuristics when the API key is not configured.

IMPORTANT: This module outputs a probability/likelihood, never a certainty.
AI detection is inherently probabilistic and should be treated as one signal
among many, not a definitive verdict.
"""
import logging
import re
import json
import math
from dataclasses import dataclass, field
from collections import Counter

from app.core.config import settings

logger = logging.getLogger(__name__)


@dataclass
class AIDetectionFlag:
    """A paragraph flagged as potentially AI-generated."""
    paragraph_index: int
    paragraph_text: str
    ai_probability: float  # 0.0 to 1.0
    reasoning: str
    detection_method: str  # "grok_analysis" or "statistical" or "combined"


@dataclass
class AIDetectionResult:
    """Output of the AI detection module.
    
    NOTE: All scores represent likelihood/probability, not certainty.
    """
    score: float  # 0-100 (higher = more likely AI-generated)
    flagged_segments: list[AIDetectionFlag]
    total_paragraphs: int
    flagged_count: int
    avg_perplexity_signal: float
    avg_burstiness_signal: float
    ai_summary: str = ""
    key_indicators: list[str] = field(default_factory=list)


# ── Statistical heuristics ───────────────────────────────────────────────────

def _compute_burstiness(text: str) -> float:
    """Compute sentence-length burstiness (variance of sentence lengths).
    
    Human writing tends to have high burstiness (varied sentence lengths).
    AI-generated text tends to have low burstiness (uniform sentence lengths).
    
    Returns a normalized score 0.0 (uniform/AI-like) to 1.0 (varied/human-like).
    """
    sentences = re.split(r'[.!?]+', text)
    sentences = [s.strip() for s in sentences if s.strip()]
    if len(sentences) < 3:
        return 0.5  # Not enough data

    lengths = [len(s.split()) for s in sentences]
    mean_len = sum(lengths) / len(lengths)
    if mean_len == 0:
        return 0.5

    variance = sum((l - mean_len) ** 2 for l in lengths) / len(lengths)
    std_dev = math.sqrt(variance)
    
    # Coefficient of variation — normalized measure
    cv = std_dev / mean_len if mean_len > 0 else 0

    # Map CV to 0-1 range. Human text typically has CV > 0.5
    # AI text typically has CV < 0.3
    return min(cv / 0.8, 1.0)


def _compute_vocabulary_richness(text: str) -> float:
    """Compute vocabulary richness as a signal.
    
    AI text often has slightly different vocabulary distribution patterns.
    Returns 0.0 (low richness, potentially AI) to 1.0 (high richness, human-like).
    """
    words = text.lower().split()
    if len(words) < 20:
        return 0.5

    unique_words = set(words)
    ttr = len(unique_words) / len(words)  # Type-token ratio

    # Hapax legomena ratio (words appearing only once)
    word_freq = Counter(words)
    hapax = sum(1 for w, c in word_freq.items() if c == 1)
    hapax_ratio = hapax / len(unique_words) if unique_words else 0

    # Combined richness score
    return min((ttr * 0.6 + hapax_ratio * 0.4) * 2, 1.0)


def _statistical_ai_score(text: str) -> tuple[float, float, float]:
    """Compute statistical AI-detection signals.
    
    Returns: (ai_probability, burstiness, vocabulary_richness)
    """
    burstiness = _compute_burstiness(text)
    vocab_richness = _compute_vocabulary_richness(text)

    # Low burstiness + moderate vocab richness = more likely AI
    # Invert burstiness since low burstiness → more AI-like
    ai_signal = ((1.0 - burstiness) * 0.6 + (1.0 - vocab_richness) * 0.4)
    
    return round(ai_signal, 3), round(burstiness, 3), round(vocab_richness, 3)


# ── Grok AI API-based analysis ──────────────────────────────────────────────

def _is_grok_configured() -> bool:
    """Check if the Grok API key is set and valid."""
    return bool(settings.GROK_API_KEY and settings.GROK_API_KEY != "your-grok-api-key-here")


async def _grok_analyze_paragraph(paragraph: str, paragraph_index: int) -> AIDetectionFlag | None:
    """Use Grok AI (xAI) to analyze a paragraph for AI-generated content.
    
    Calls the Grok API at https://api.x.ai/v1 using OpenAI-compatible format.
    """
    if not _is_grok_configured():
        return None

    try:
        from openai import AsyncOpenAI

        client = AsyncOpenAI(
            base_url=settings.GROK_BASE_URL,
            api_key=settings.GROK_API_KEY,
            timeout=15.0,
        )

        response = await client.chat.completions.create(
            model=settings.GROK_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an expert AI-content detection analyst. Analyze the given paragraph "
                        "and estimate the probability it was generated by an AI language model (like ChatGPT, "
                        "Claude, Gemini, etc.).\n\n"
                        "Consider these signals:\n"
                        "- Sentence structure patterns (AI tends to be more uniform)\n"
                        "- Vocabulary choices and hedging language\n"
                        "- Transition phrases (AI overuses 'furthermore', 'moreover', 'additionally')\n"
                        "- Repetitive patterns and formulaic structure\n"
                        "- Lack of personal voice or idiosyncratic expressions\n"
                        "- Overly polished or generic academic language\n\n"
                        "Respond with ONLY a valid JSON object, no other text:\n"
                        '{"ai_probability": <float 0.0 to 1.0>, "reasoning": "<brief explanation>"}'
                    ),
                },
                {
                    "role": "user",
                    "content": f"Analyze this paragraph for AI-generated content:\n\n{paragraph[:2000]}"
                },
            ],
            temperature=0.1,
            max_tokens=300,
        )

        content = response.choices[0].message.content.strip()
        
        # Parse the JSON response (handle markdown code blocks)
        if "```" in content:
            match = re.search(r'```(?:json)?\s*(.*?)\s*```', content, re.DOTALL)
            content = match.group(1) if match else content
        
        # Try to extract JSON from the response
        json_match = re.search(r'\{[^{}]*\}', content)
        if json_match:
            content = json_match.group(0)
        
        result = json.loads(content)
        ai_prob = float(result.get("ai_probability", 0.5))
        reasoning = result.get("reasoning", "No reasoning provided")

        if ai_prob >= 0.5:
            return AIDetectionFlag(
                paragraph_index=paragraph_index,
                paragraph_text=paragraph[:500],
                ai_probability=round(ai_prob, 3),
                reasoning=reasoning,
                detection_method="grok_analysis",
            )

    except json.JSONDecodeError as e:
        logger.warning(f"Grok AI response JSON parse error for paragraph {paragraph_index}: {e}")
    except Exception as e:
        logger.warning(f"Grok AI analysis failed for paragraph {paragraph_index}: {e}")

    return None


async def _grok_analyze_full_document(text: str) -> dict | None:
    """Use Grok AI for a holistic document-level AI detection analysis.
    
    This provides an overall assessment in addition to per-paragraph analysis.
    """
    if not _is_grok_configured():
        return None

    try:
        from openai import AsyncOpenAI

        client = AsyncOpenAI(
            base_url=settings.GROK_BASE_URL,
            api_key=settings.GROK_API_KEY,
            timeout=30.0,
        )

        # Truncate for API limits
        truncated_text = text[:4000]

        response = await client.chat.completions.create(
            model=settings.GROK_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an expert academic and professional document evaluator specializing in "
                        "AI detection, originality assessment, and authorship authenticity analysis.\n\n"
                        "Evaluate the text thoroughly for:\n"
                        "1. Originality & Human Voice: personal experiences, idiosyncratic phrasing, authentic projects, specific timelines.\n"
                        "2. AI Generation Markers: uniform sentence structure, formulaic transitions ('furthermore', 'additionally'), generic claims, lack of personal perspective.\n"
                        "3. Content Credibility: concrete verifiable details vs vague boilerplate.\n\n"
                        "Respond with ONLY a valid JSON object, no markdown, no other text:\n"
                        '{"overall_ai_probability": <float 0.0 to 1.0>, '
                        '"originality_score": <float 0.0 to 100.0>, '
                        '"confidence": <float 0.0 to 1.0>, '
                        '"summary": "<Detailed 2-3 sentence assessment of the document voice, authenticity, and patterns>", '
                        '"key_indicators": ["<specific observation 1>", "<specific observation 2>", "<specific observation 3>"]}'
                    ),
                },
                {
                    "role": "user",
                    "content": f"Analyze this document for authenticity, originality, and AI-generated content:\n\n{truncated_text}"
                },
            ],
            temperature=0.1,
            max_tokens=500,
        )

        content = response.choices[0].message.content.strip()
        
        if "```" in content:
            match = re.search(r'```(?:json)?\s*(.*?)\s*```', content, re.DOTALL)
            content = match.group(1) if match else content

        json_match = re.search(r'\{[^{}]*\}', content)
        if json_match:
            try:
                return json.loads(json_match.group(0))
            except Exception:
                pass

        return json.loads(content)

    except Exception as e:
        logger.warning(f"Grok AI full-document analysis failed: {e}")
        return None


def _split_into_paragraphs(clean_text: str) -> list[str]:
    """Smart paragraph splitter handling academic papers, essays, and resumes."""
    # Try double-newline first
    raw_paras = [p.strip() for p in clean_text.split("\n\n") if len(p.strip()) > 30]
    if len(raw_paras) > 1:
        return raw_paras

    # Group lines for documents (like resumes/PDFs) with single line breaks
    lines = [l.strip() for l in clean_text.split("\n") if l.strip()]
    if len(lines) > 2:
        chunks = []
        current = []
        current_len = 0
        for line in lines:
            # Detect section boundaries or bullet points
            is_header = (
                (line.isupper() and len(line) < 40)
                or line.endswith(":")
                or line.startswith(("(cid:", "•", "-", "*", "1.", "2.", "3."))
            )
            if is_header and current_len > 80:
                chunks.append("\n".join(current))
                current = [line]
                current_len = len(line)
            else:
                current.append(line)
                current_len += len(line)
                if current_len >= 350:
                    chunks.append("\n".join(current))
                    current = []
                    current_len = 0
        if current:
            chunks.append("\n".join(current))
        if len(chunks) > 1:
            return chunks

    # Fallback to sentence groupings
    sentences = re.split(r'(?<=[.!?])\s+', clean_text)
    if len(sentences) >= 4:
        return [" ".join(sentences[i:i+3]) for i in range(0, len(sentences), 3)]

    return [clean_text] if clean_text.strip() else []


# ── Main entry point ─────────────────────────────────────────────────────────

async def detect_ai_content(
    clean_text: str,
    sentences: list,
    threshold: float = 0.5,
) -> AIDetectionResult:
    """Run AI content detection on the document.
    
    Uses Grok AI (xAI) for intelligent analysis when API key is configured,
    with statistical heuristics as fallback/complement.
    """
    paragraphs = _split_into_paragraphs(clean_text)

    if not paragraphs:
        return AIDetectionResult(
            score=0.0, flagged_segments=[], total_paragraphs=0,
            flagged_count=0, avg_perplexity_signal=0.0, avg_burstiness_signal=0.0,
            ai_summary="Document text was empty.",
            key_indicators=[],
        )

    grok_available = _is_grok_configured()
    if grok_available:
        logger.info("Grok AI API configured — using LLM-powered AI detection")
    else:
        logger.info("Grok API key not set — using statistical heuristics only")

    flagged: list[AIDetectionFlag] = []
    burstiness_signals: list[float] = []
    vocab_signals: list[float] = []

    # Run document-level Grok analysis
    doc_analysis = None
    ai_summary = ""
    key_indicators = []
    doc_ai_prob = 0.0
    if grok_available:
        doc_analysis = await _grok_analyze_full_document(clean_text)
        if doc_analysis:
            ai_summary = doc_analysis.get("summary", "")
            key_indicators = doc_analysis.get("key_indicators", [])
            doc_ai_prob = float(doc_analysis.get("overall_ai_probability", 0.0))
            logger.info(
                f"Grok document-level analysis: "
                f"ai_prob={doc_ai_prob}, "
                f"confidence={doc_analysis.get('confidence', 'N/A')}"
            )

    # Paragraph-level evaluation using statistical heuristics
    for idx, paragraph in enumerate(paragraphs):
        stat_score, burstiness, vocab = _statistical_ai_score(paragraph)
        burstiness_signals.append(burstiness)
        vocab_signals.append(vocab)

        # Flag if statistical heuristics or document-level signals indicate synthetic generation
        effective_ai_prob = (stat_score * 0.4 + doc_ai_prob * 0.6) if doc_analysis else stat_score
        if effective_ai_prob >= threshold:
            flagged.append(AIDetectionFlag(
                paragraph_index=idx,
                paragraph_text=paragraph[:500],
                ai_probability=round(effective_ai_prob, 3),
                reasoning="Uniform sentence structure and low burstiness characteristic of AI-generated phrasing.",
                detection_method="combined" if doc_analysis else "statistical",
            ))

    flagged_count = len(flagged)
    total = len(paragraphs)
    
    # Calculate realistic AI risk score
    doc_ai_prob = float(doc_analysis.get("overall_ai_probability", 0.0)) if doc_analysis else 0.0

    if flagged:
        avg_prob = sum(f.ai_probability for f in flagged) / flagged_count
        paragraph_score = (flagged_count / total) * avg_prob * 100
        if doc_analysis:
            score = round(paragraph_score * 0.5 + doc_ai_prob * 100 * 0.5, 1)
        else:
            score = round(paragraph_score, 1)
    elif doc_analysis:
        score = round(doc_ai_prob * 100, 1)
    else:
        avg_stat = sum(vocab_signals) / len(vocab_signals) if vocab_signals else 0.0
        score = round(avg_stat * 30.0, 1)

    # Provide default summary if none from LLM
    if not ai_summary:
        if score < 25:
            ai_summary = "Verified authentic human writing. Strong idiosyncratic voice, high sentence burstiness, and natural stylistic variations."
            key_indicators = ["High syntactic burstiness", "Natural vocabulary distribution", "Consistent authorial voice"]
        elif score < 55:
            ai_summary = "Moderate AI characteristics detected. Some sections show uniform phrasing and structured transitions."
            key_indicators = ["Structured paragraph uniformity", "Standard academic transitions"]
        else:
            ai_summary = "High probability of AI-generated content. Persistent formulaic structure, hedging language, and repetitive syntax patterns."
            key_indicators = ["Formulaic transitions", "Low syntactic burstiness", "Overly generic phrasing"]

    avg_burst = sum(burstiness_signals) / len(burstiness_signals) if burstiness_signals else 0.0
    avg_vocab = sum(vocab_signals) / len(vocab_signals) if vocab_signals else 0.0

    method = "Grok AI + Statistical" if grok_available else "Statistical only"
    logger.info(f"AI detection ({method}): {flagged_count}/{total} paragraphs flagged, score={score}")

    return AIDetectionResult(
        score=min(max(score, 0.0), 100.0),
        flagged_segments=flagged,
        total_paragraphs=total,
        flagged_count=flagged_count,
        avg_perplexity_signal=round(1.0 - avg_vocab, 3),
        avg_burstiness_signal=round(avg_burst, 3),
        ai_summary=ai_summary,
        key_indicators=key_indicators,
    )
